"""Regenerates js/examples-extra.js from the shader files in this folder.

Run after editing any of the shaders here, then reload the app:
    python shaders/build_examples.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "js", "examples-extra.js")

# (dropdown name, file in this folder)
EXAMPLES = [
    ("Light shimmering on water", "water_shimmer.glsl"),
    ("Lava volcano (raymarched)", "lava_volcano.glsl"),
    ("Fire & ice, glitchy", "fire_and_ice.glsl"),
    ("Dancing shadows around a campfire", "dancing_shadows.glsl"),
    ("Dancing shadows with feedback trails (multi-pass)", "dancing_shadows_feedback.shader.json"),
    ("Crowd shadows on a sunset wall", "crowd_shadows.glsl"),
    ("Celestial sparkles on water (bokeh)", "celestial_sparkles.glsl"),
    ("Lemon juice sparkle gold", "lemon_sparkle_gold.glsl"),
    ("Ancient green (abstract)", "ancient_green.glsl"),
    ("Ancient green glyphs (beat-synced)", "ancient_green_glyphs.glsl"),
    ("Thunderstorm with lightning", "thunderstorm.glsl"),
]


def read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read()


entries = []
for title, name in EXAMPLES:
    if name.endswith(".json"):
        proj = json.loads(read(name))
        entry = {"name": title, "file": name, "common": proj.get("common"), "passes": proj["passes"]}
    else:
        entry = {"name": title, "file": name, "code": read(name)}
    entries.append(entry)

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("'use strict';\n\n")
    f.write("// GENERATED by shaders/build_examples.py from the files in shaders/.\n")
    f.write("// Edit those files and rerun the script instead of editing this one.\n\n")
    f.write("window.SHADER_EXAMPLES.push(\n")
    f.write(",\n".join(json.dumps(e, indent=2, ensure_ascii=False) for e in entries))
    f.write("\n);\n")

print(f"Wrote {os.path.normpath(OUT)} with {len(entries)} examples")
